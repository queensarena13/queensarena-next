create policy "Public read leagues"
  on public.leagues for select
  using (true);

create policy "Public read teams"
  on public.teams for select
  using (true);

create policy "Public read players"
  on public.players for select
  using (true);

create policy "Public read roster memberships"
  on public.roster_memberships for select
  using (true);

create policy "Public read player season stats"
  on public.player_season_stats for select
  using (true);

create policy "Public read team season stats"
  on public.team_season_stats for select
  using (true);

create policy "Public read matches"
  on public.matches for select
  using (true);

create policy "Public read standings"
  on public.standings for select
  using (true);

create policy "Public read notifications"
  on public.notifications for select
  using (true);

create policy "Users read own favorites"
  on public.favorites for select
  using (auth.uid() = user_id);

create policy "Users insert own favorites"
  on public.favorites for insert
  with check (auth.uid() = user_id);

create policy "Users delete own favorites"
  on public.favorites for delete
  using (auth.uid() = user_id);
